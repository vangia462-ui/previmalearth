# Primeval Earth Mobile Script

Script Auto Farm + ESP cho game Primeval Earth (Roblox).
Tối ưu cho Android Executor (Arceus X, Hydrogen, Delta, Codex).

## Tính năng
- Auto Eat / Drink / Rest / Zone
- Auto Farm Fossil
- Fly Mode (bay lơ lửng)
- ESP: Players, Fossils, Trees, Water
- GUI đẹp, kéo thả, phím tắt

